<#
.SYNOPSIS
  Runs the tests batch-remediate wrote for work item {id}: {title}

.DESCRIPTION
  Generated by batch-remediate (tests mode) on {RUN_TAG} for commit {sha}.
  The same script is posted in the work item's "TESTS WRITTEN" comment and committed at
  {RUN_SCRIPT_PATH}. Windows PowerShell 5.1 or PowerShell 7. Safe to re-run.

  Layers
    unit   C# MSTest tests in category {TEST_CATEGORY}
    js     jest specs for {id} (client-side)
    e2e    browser spec, headless, against Dev - only after the merge is deployed to Dev
    watch  the same browser spec in Edge, slowed down, for a tester to watch
    all    unit + js (the default; what you run before merge)

  Results go to {RESULTS_DIR}\<time>\ (TRX, jest JSON, Playwright JSON, summary.json).
  Nothing is posted to the work item. To post: /batch-remediate results {id}

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File .\{id}-run-tests.ps1
.EXAMPLE
  powershell -ExecutionPolicy Bypass -File .\{id}-run-tests.ps1 -Layer e2e
.EXAMPLE
  powershell -ExecutionPolicy Bypass -File .\{id}-run-tests.ps1 -Layer watch
#>
[CmdletBinding()]
param(
  [string[]]$Layer = @('unit', 'js'),
  [string]$RepoRoot = '',
  [switch]$ListOnly,
  [switch]$Force
)

# ---------------------------------------------------------------------------------------------
# Filled in by batch-remediate. Edit only if a path moved.
# ---------------------------------------------------------------------------------------------
$Ticket        = '{id}'
$TestCategory  = '{TEST_CATEGORY}'                 # e.g. TICKET-361204
$TestCommit    = '{sha}'                           # the commit that added these tests
$Branch        = '{branch}'                        # where they live until merged into develop
$DevHost       = 'symphonywebdev.azurewebsites.net'
$CsTests       = @(
  # Runner 'dotnet' = dotnet test on a .csproj; 'vstest' = vstest.console.exe on a built .dll
  @{ Path = '{path/to/Project.Tests.csproj}'; Runner = 'dotnet' }
)
$JsUnitDir     = 'symphonyModernization/tests/unit'
$JsSpecs       = @('{slug}-{id}')                  # jest path patterns (file names without .spec.js)
$E2ERoot       = 'symphonyModernization/tests'
$E2ESpec       = 'e2e/{id}-{slug}.spec.js'         # '' when the story has no browser-visible change
$Expected      = @('AC-1', 'AC-2', 'DOD-1')        # every requirement an automated test covers
$ManualOnly    = @{ }                              # e.g. @{ 'AC-4' = 'needs a real mailbox; tester checks it' }
$ResultsDir    = '{RESULTS_DIR}'                   # relative to the repo root
# ---------------------------------------------------------------------------------------------

$ErrorActionPreference = 'Stop'
$script:Problems = 0
function Say($m)   { Write-Host "  $m" }
function Ok($m)    { Write-Host "  [ok]   $m" -ForegroundColor Green }
function Warn($m)  { Write-Host "  [warn] $m" -ForegroundColor Yellow }
function Stop-With($problem, $fix) {
  Write-Host ""
  Write-Host "  [STOP] $problem" -ForegroundColor Red
  Write-Host "         Fix: $fix" -ForegroundColor Yellow
  Write-Host ""
  exit 2
}
function Invoke-Native {
  # Windows PowerShell 5.1 turns native stderr into errors under 'Stop'; relax it for the call.
  param([string]$Exe, [string[]]$Arguments)
  $ErrorActionPreference = 'Continue'
  & $Exe @Arguments 2>&1 | ForEach-Object { Write-Host "    $_" }
  return $LASTEXITCODE
}
function NP([string]$s) { return ($s -replace '[\\/]', [IO.Path]::DirectorySeparatorChar) }   # native path
function Get-ReqId([string]$text) {
  # AC1_Name, ACrepro_Name, "AC-2 - title", "DOD-1 ..." -> AC-1 / AC-repro / AC-2 / DOD-1
  $m = [regex]::Match($text, '(?<![A-Za-z])(AC|DOD)-?([0-9]+|repro|regress)(?![0-9A-Za-z])')
  if ($m.Success) { return ('{0}-{1}' -f $m.Groups[1].Value.ToUpper(), $m.Groups[2].Value) }
  return ''
}

# Layers: accept "unit,js" as one argument as well as an array
$Layer = @($Layer | ForEach-Object { $_ -split ',' } | ForEach-Object { $_.Trim().ToLower() } | Where-Object { $_ })
if ($Layer -contains 'all') { $Layer = @('unit', 'js') + @($Layer | Where-Object { $_ -ne 'all' }) }
foreach ($l in $Layer) {
  if (@('unit', 'js', 'e2e', 'watch') -notcontains $l) { Stop-With "Unknown layer '$l'." "Use -Layer unit, js, e2e, watch or all." }
}

Write-Host ""
Write-Host "Tests for $Ticket - layers: $($Layer -join ', ')$(if ($ListOnly) { ' (list only)' })"
Write-Host ""

# ---- 1. Repo root ---------------------------------------------------------------------------
$git = (Get-Command git -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1).Source
if (-not $git) { Stop-With "git is not on PATH." "Install Git for Windows, open a new window, re-run." }
function Find-Root([string]$from) {
  if (-not $from -or -not (Test-Path $from)) { return '' }
  $ErrorActionPreference = 'Continue'
  $r = & $git -C $from rev-parse --show-toplevel 2>$null
  if ($LASTEXITCODE -eq 0 -and $r -and (Test-Path (Join-Path $r 'symphonyModernization'))) { return (NP $r) }
  return ''
}
$here = if ($PSScriptRoot) { $PSScriptRoot } else { Split-Path -Parent $MyInvocation.MyCommand.Path }
$root = ''
foreach ($c in @($RepoRoot, (Get-Location).Path, $here, (Join-Path $HOME (NP 'source/repos/Symphony Cloud')))) {
  $root = Find-Root $c
  if ($root) { break }
}
if (-not $root) { Stop-With "Could not find the Symphony Cloud repository." "cd into your clone (or the story's worktree) and re-run, or pass -RepoRoot <path>." }
Ok "repo: $root"

# ---- 2. Does this checkout contain the tests? ------------------------------------------------
$ErrorActionPreference = 'Continue'
$head = (& $git -C $root rev-parse HEAD 2>$null | Out-String).Trim()
$headBranch = (& $git -C $root rev-parse --abbrev-ref HEAD 2>$null | Out-String).Trim()
& $git -C $root cat-file -e "$TestCommit^{commit}" 2>$null
$known = ($LASTEXITCODE -eq 0)
$contains = $false
if ($known) { & $git -C $root merge-base --is-ancestor $TestCommit HEAD 2>$null; $contains = ($LASTEXITCODE -eq 0) }
$ErrorActionPreference = 'Stop'
if (-not $contains) {
  $why = if ($known) { "HEAD ($headBranch) does not contain the test commit $($TestCommit.Substring(0, [Math]::Min(8, $TestCommit.Length)))." } else { "The test commit $TestCommit is not in this clone yet." }
  if ($Force) { Warn "$why Continuing because of -Force." }
  else { Stop-With $why "git -C `"$root`" fetch origin; git -C `"$root`" checkout $Branch   (or develop, once merged); then re-run." }
} else { Ok "checkout $headBranch at $($head.Substring(0, 8)) contains the tests" }

# ---- 3. Output folder ------------------------------------------------------------------------
$stamp  = Get-Date -Format 'yyyyMMdd-HHmmss'
$outDir = Join-Path $root (Join-Path (NP $ResultsDir) $stamp)
New-Item -ItemType Directory -Path $outDir -Force | Out-Null
$results = New-Object System.Collections.ArrayList   # one row per test: layer, name, req, outcome
$layers  = [ordered]@{}

function Add-Result($layer, $name, $outcome) {
  [void]$results.Add([pscustomobject]@{ layer = $layer; name = $name; req = (Get-ReqId $name); outcome = $outcome })
}
function Need-Tool($name, $fix) {
  if (-not (Get-Command $name -ErrorAction SilentlyContinue)) { Stop-With "$name is not on PATH." $fix }
}

# ---- 4. unit: C# MSTest by category ----------------------------------------------------------
if ($Layer -contains 'unit') {
  Write-Host ""; Write-Host "[unit] C# tests in category $TestCategory"
  $p = 0; $f = 0; $s = 0
  foreach ($t in $CsTests) {
    $path = Join-Path $root (NP $t.Path)
    if (-not (Test-Path $path)) { Stop-With "Test project not found: $($t.Path)" "Pull the branch, or fix `$CsTests at the top of this script." }
    $leaf = [IO.Path]::GetFileNameWithoutExtension($path)
    $trx  = "$leaf.trx"
    if ($t.Runner -eq 'vstest') {
      $vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
      if (-not (Test-Path $vswhere)) { Stop-With "vstest.console.exe not found (no Visual Studio)." "Install Visual Studio or its Build Tools with the testing workload." }
      $vstest = & $vswhere -latest -products * -find '**\vstest.console.exe' | Select-Object -First 1
      if ($ListOnly) { $code = Invoke-Native $vstest @($path, '/ListTests', "/TestCaseFilter:TestCategory=$TestCategory"); continue }
      $code = Invoke-Native $vstest @($path, "/TestCaseFilter:TestCategory=$TestCategory", "/Logger:trx;LogFileName=$trx", "/ResultsDirectory:$outDir")
    } else {
      Need-Tool 'dotnet' 'Install the .NET SDK the solution uses, open a new window, re-run.'
      if ($ListOnly) { $code = Invoke-Native 'dotnet' @('test', $path, '--list-tests', '--filter', "TestCategory=$TestCategory"); continue }
      $code = Invoke-Native 'dotnet' @('test', $path, '--filter', "TestCategory=$TestCategory", '--logger', "trx;LogFileName=$trx", '--results-directory', $outDir)
    }
    $trxPath = Get-ChildItem -Path $outDir -Filter $trx -Recurse -ErrorAction SilentlyContinue | Select-Object -First 1
    if (-not $trxPath) { Warn "$leaf produced no results (exit $code) - build error? Scroll up."; $f++; $script:Problems++; continue }
    [xml]$x = [IO.File]::ReadAllText($trxPath.FullName)
    foreach ($r in @($x.TestRun.Results.UnitTestResult)) {
      if (-not $r) { continue }
      $o = switch ($r.outcome) { 'Passed' { 'passed' } 'Failed' { 'failed' } default { 'skipped' } }
      Add-Result 'unit' $r.testName $o
      if ($o -eq 'passed') { $p++ } elseif ($o -eq 'failed') { $f++ } else { $s++ }
    }
  }
  if (-not $ListOnly) {
    if (($p + $f + $s) -eq 0) { Warn "no C# test carries [TestCategory(`"$TestCategory`")]"; $script:Problems++ }
    $layers['unit'] = [ordered]@{ passed = $p; failed = $f; skipped = $s }
  }
}

# ---- 5. js: jest -----------------------------------------------------------------------------
if ($Layer -contains 'js' -and $JsSpecs.Count -gt 0) {
  Write-Host ""; Write-Host "[js] jest specs: $($JsSpecs -join ', ')"
  Need-Tool 'node' 'Install Node.js 18 or later, open a new window, re-run.'
  $jsDir = Join-Path $root (NP $JsUnitDir)
  $jest  = Join-Path $jsDir (NP 'node_modules/jest/bin/jest.js')
  if (-not (Test-Path $jest)) { Stop-With "jest is not installed in $JsUnitDir." "npm --prefix `"$jsDir`" ci   then re-run." }
  $json = Join-Path $outDir 'jest.json'
  Push-Location $jsDir
  try {
    if ($ListOnly) { $code = Invoke-Native 'node' (@($jest, '--listTests') + $JsSpecs) }
    else { $code = Invoke-Native 'node' (@($jest, '--json', "--outputFile=$json") + $JsSpecs) }
  } finally { Pop-Location }
  if (-not $ListOnly) {
    $p = 0; $f = 0; $s = 0
    if (Test-Path $json) {
      $j = [IO.File]::ReadAllText($json) | ConvertFrom-Json
      foreach ($file in @($j.testResults)) {
        foreach ($a in @($file.assertionResults)) {
          $o = switch ($a.status) { 'passed' { 'passed' } 'failed' { 'failed' } default { 'skipped' } }
          Add-Result 'js' $a.fullName $o
          if ($o -eq 'passed') { $p++ } elseif ($o -eq 'failed') { $f++ } else { $s++ }
        }
      }
    } else { Warn "jest wrote no results (exit $code) - scroll up."; $f++ }
    if (($p + $f + $s) -eq 0) { Warn "jest found no tests for $($JsSpecs -join ', ')"; $script:Problems++ }
    $layers['js'] = [ordered]@{ passed = $p; failed = $f; skipped = $s }
  }
}

# ---- 6. e2e / watch: Playwright against Dev --------------------------------------------------
$browser = @($Layer | Where-Object { $_ -eq 'e2e' -or $_ -eq 'watch' })
if ($browser.Count -gt 0) {
  if (-not $E2ESpec) { Warn "this story has no browser spec - nothing to run for $($browser -join ', ')" }
  else {
    Need-Tool 'node' 'Install Node.js 18 or later, open a new window, re-run.'
    $e2eDir = Join-Path $root (NP $E2ERoot)
    $pwCli  = Join-Path $e2eDir (NP 'node_modules/@playwright/test/cli.js')
    if (-not (Test-Path $pwCli)) { Stop-With "Playwright is not installed in $E2ERoot." "npm --prefix `"$e2eDir`" ci; npm --prefix `"$e2eDir`" exec playwright install chromium   then re-run." }
    # Dev only: refuse any other BASE_URL
    $envFile = Join-Path $e2eDir '.env'
    if (Test-Path $envFile) {
      $base = (Select-String -Path $envFile -Pattern '^\s*BASE_URL\s*=\s*(\S+)' | Select-Object -First 1)
      if ($base -and $base.Matches[0].Groups[1].Value -notmatch [regex]::Escape($DevHost)) {
        Stop-With "BASE_URL in $E2ERoot\.env is not Dev ($($base.Matches[0].Groups[1].Value))." "These tests only run against https://$DevHost - fix .env."
      }
    }
    if (-not $ListOnly) {
      $state = Join-Path $e2eDir 'auth-state.json'
      if (-not (Test-Path $state)) { Stop-With "No saved Dev sign-in ($E2ERoot\auth-state.json)." "npm --prefix `"$e2eDir`" run auth   (a browser opens; you sign in yourself), then re-run." }
      $age = (New-TimeSpan -Start (Get-Item $state).LastWriteTime -End (Get-Date)).TotalHours
      if ($age -gt 8) { Stop-With ("The saved sign-in is {0:N0} hours old." -f $age) "npm --prefix `"$e2eDir`" run auth   then re-run." }
      Ok ("saved sign-in is {0:N1} hours old" -f $age)
    }
    $spec = $E2ESpec -replace '\\', '/'
    Push-Location $e2eDir
    try {
      foreach ($l in $browser) {
        Write-Host ""; Write-Host "[$l] $spec against https://$DevHost"
        if ($ListOnly) { $code = Invoke-Native 'node' @($pwCli, 'test', '--config', 'playwright.e2e.config.js', '--list', $spec); continue }
        if ($l -eq 'watch') {
          $code = Invoke-Native 'node' @('tools/run-e2e.js', '--watch', $spec)
          Say "watched run finished (exit $code). The tester's verdicts are recorded with /verify-ticket $Ticket."
          continue
        }
        $json = Join-Path $outDir 'playwright.json'
        $env:PLAYWRIGHT_JSON_OUTPUT_NAME = $json
        $env:PLAYWRIGHT_JSON_OUTPUT_FILE = $json
        $env:E2E_STRICT = '1'
        $code = Invoke-Native 'node' @($pwCli, 'test', '--config', 'playwright.e2e.config.js', '--reporter=list,json', $spec)
        $p = 0; $f = 0; $s = 0
        if (Test-Path $json) {
          $pj = [IO.File]::ReadAllText($json) | ConvertFrom-Json
          $stack = New-Object System.Collections.Stack
          foreach ($su in @($pj.suites)) { $stack.Push($su) }
          while ($stack.Count -gt 0) {
            $su = $stack.Pop()
            foreach ($c in @($su.suites)) { if ($c) { $stack.Push($c) } }
            foreach ($sp in @($su.specs)) {
              if (-not $sp) { continue }
              $st = @($sp.tests | ForEach-Object { @($_.results)[-1].status })
              $o = if ($st -contains 'failed' -or $st -contains 'timedOut' -or $st -contains 'interrupted') { 'failed' } elseif ($st -contains 'passed') { 'passed' } else { 'skipped' }
              Add-Result 'e2e' $sp.title $o
              if ($o -eq 'passed') { $p++ } elseif ($o -eq 'failed') { $f++ } else { $s++ }
            }
          }
        } else { Warn "Playwright wrote no results (exit $code) - scroll up."; $f++ }
        if ($s -gt 0) { Warn "$s browser test(s) skipped - usually the sign-in or Dev was unreachable. Skipped proves nothing." }
        $layers['e2e'] = [ordered]@{ passed = $p; failed = $f; skipped = $s }
      }
    } finally { Pop-Location }
  }
}

if ($ListOnly) { Write-Host ""; Ok "listed (nothing was run)"; exit 0 }

# ---- 7. Summary ------------------------------------------------------------------------------
$byReq = [ordered]@{}
foreach ($id in $Expected) { $byReq[$id] = 'not run' }
foreach ($r in $results) {
  if (-not $r.req) { continue }
  $cur = $byReq[$r.req]
  if ($r.outcome -eq 'failed') { $byReq[$r.req] = 'failed' }
  elseif ($r.outcome -eq 'passed' -and $cur -ne 'failed') { $byReq[$r.req] = 'passed' }
  elseif (-not $cur -or $cur -eq 'not run') { $byReq[$r.req] = $r.outcome }
}
foreach ($k in $ManualOnly.Keys) { $byReq[$k] = "manual - $($ManualOnly[$k])" }
$notRun = @($byReq.Keys | Where-Object { $byReq[$_] -eq 'not run' })
if ($notRun.Count -gt 0 -and ($Layer -contains 'unit' -or $Layer -contains 'js' -or $Layer -contains 'e2e')) {
  # A requirement is only 'not run' overall if no layer that ran covered it; browser-only ones
  # stay 'not run' until -Layer e2e runs after the Dev deploy - that is expected before merge.
  Warn "no test ran for: $($notRun -join ', ')"
}

$summary = [ordered]@{
  ticket      = $Ticket
  commit      = $head
  branch      = $headBranch
  testCommit  = $TestCommit
  machine     = $env:COMPUTERNAME
  user        = $env:USERNAME
  startedAt   = (Get-Date).ToString('o')
  source      = 'developer'                  # e2e from here is source=local - never proof
  layers      = $layers
  requirements = $byReq
  tests       = $results
}
$summaryPath = Join-Path $outDir 'summary.json'
[IO.File]::WriteAllText($summaryPath, ($summary | ConvertTo-Json -Depth 6))

Write-Host ""
Write-Host "Results for $Ticket at $($head.Substring(0, 8))"
foreach ($k in $layers.Keys) {
  $v = $layers[$k]
  $color = if ($v.failed -gt 0) { 'Red' } elseif ($v.skipped -gt 0) { 'Yellow' } else { 'Green' }
  Write-Host ("  {0,-6} passed {1,3}   failed {2,3}   skipped {3,3}" -f $k, $v.passed, $v.failed, $v.skipped) -ForegroundColor $color
}
Write-Host ""
foreach ($k in $byReq.Keys) {
  $v = [string]$byReq[$k]
  $color = if ($v -eq 'passed') { 'Green' } elseif ($v -eq 'failed') { 'Red' } else { 'Yellow' }
  Write-Host ("  {0,-10} {1}" -f $k, $v) -ForegroundColor $color
}
Write-Host ""
Say "summary: $summaryPath"
Say "post to the story: /batch-remediate results $Ticket"
Write-Host ""

$failed = 0
foreach ($v in $layers.Values) { $failed += $v.failed }
if ($failed -gt 0 -or $script:Problems -gt 0) { exit 1 }
exit 0
